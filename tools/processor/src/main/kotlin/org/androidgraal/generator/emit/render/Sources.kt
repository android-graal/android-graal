package org.androidgraal.generator.emit.render

import com.palantir.javapoet.ClassName
import com.palantir.javapoet.CodeBlock
import com.palantir.javapoet.FieldSpec
import com.palantir.javapoet.JavaFile
import com.palantir.javapoet.MethodSpec
import com.palantir.javapoet.ParameterizedTypeName
import com.palantir.javapoet.TypeName
import com.palantir.javapoet.TypeSpec
import org.androidgraal.common.Side
import org.androidgraal.generator.emit.JavaNames
import org.androidgraal.generator.emit.codec.Codecs
import org.androidgraal.generator.emit.codec.ReceiverBody
import org.androidgraal.generator.emit.codec.SenderBody
import org.androidgraal.generator.emit.codec.Wire
import org.androidgraal.generator.emit.codec.handlesFieldOf
import org.androidgraal.generator.emit.zeroOf
import org.androidgraal.generator.model.BridgeModel
import org.androidgraal.generator.model.Proxy
import javax.lang.model.element.Modifier.FINAL
import javax.lang.model.element.Modifier.PRIVATE
import javax.lang.model.element.Modifier.PUBLIC
import javax.lang.model.element.Modifier.STATIC

internal abstract class Sources(internal val model: BridgeModel, private val side: Side) {
    private val codecs = Codecs(model, side)

    internal val fingerprintField: FieldSpec = FieldSpec.builder(TypeName.LONG, "FINGERPRINT", PRIVATE, STATIC, FINAL)
        .initializer("0x\$LL", "%016x".format(model.fingerprint()))
        .build()

    internal val handlesField: FieldSpec = handlesFieldOf(side)

    internal val privateConstructor: MethodSpec = MethodSpec.constructorBuilder().addModifiers(PRIVATE).build()

    private val proxyConstructor: MethodSpec = MethodSpec.constructorBuilder()
        .addModifiers(PRIVATE)
        .addParameter(TypeName.LONG, "id")
        .addStatement("super(id)")
        .build()

    internal abstract val threadData: ClassName

    internal abstract val pending: CodeBlock

    internal abstract val raise: CodeBlock

    internal abstract fun contractClass(): TypeSpec

    internal abstract fun endPointOf(wire: Wire): MethodSpec.Builder

    internal abstract fun proxyFieldsOf(wires: List<Wire>): List<FieldSpec>

    internal abstract fun proxyMethodsOf(proxy: Proxy, wires: List<Wire>): List<MethodSpec>

    internal abstract fun sendCall(body: SenderBody, wire: Wire, values: List<CodeBlock>): CodeBlock

    fun render(): Map<String, String> {
        val files = linkedMapOf<String, String>()
        val dir = model.packageName.replace('.', '/')
        files["$dir/${model.contractClass.simpleName()}.java"] = sourceOf(contractClass())
        model.proxies.forEach { proxy ->
            val name = model.generatedClass(proxy)
            val type = if (proxy.implementation == side) endPointClassOf(proxy, name) else proxyClassOf(proxy, name)
            files["$dir/${name.simpleName()}.java"] = sourceOf(type)
        }
        return files
    }

    internal fun overrideOf(name: String, returns: TypeName): MethodSpec.Builder =
        MethodSpec.methodBuilder(name).addAnnotation(Override::class.java).addModifiers(PUBLIC).returns(returns)

    internal fun overridesOf(wires: List<Wire>): List<MethodSpec> = wires.map { overrideMethodOf(it) }

    private fun sourceOf(type: TypeSpec): String {
        return JavaFile.builder(model.packageName, type)
            .addFileComment("\$L", "Generated by android-graal.")
            .skipJavaLangImports(true)
            .indent("    ")
            .build()
            .toString()
    }

    private fun endPointClassOf(proxy: Proxy, name: ClassName): TypeSpec {
        val wires = codecs.wiresOf(proxy)
        val type = TypeSpec.classBuilder(name).addModifiers(PUBLIC, FINAL)
            .addFields((listOf(handlesField) + codecs.fieldsOf(wires)).distinct())
            .addMethod(privateConstructor)
        wires.forEach { type.addMethod(endPointOf(it).addCode(receiverBodyOf(it)).build()) }
        return type.addTypes(codecs.typesOf(wires)).build()
    }

    private fun proxyClassOf(proxy: Proxy, name: ClassName): TypeSpec {
        val wires = codecs.wiresOf(proxy)
        return TypeSpec.classBuilder(name).addModifiers(PUBLIC, FINAL)
            .superclass(JavaNames.FOREIGN)
            .addSuperinterface(ClassName.get(proxy.type))
            .addFields(codecs.fieldsOf(wires))
            .addField(proxiesFieldOf(name))
            .addFields(proxyFieldsOf(wires))
            .addMethod(proxyConstructor)
            .addMethods(proxyMethodsOf(proxy, wires))
            .addTypes(codecs.typesOf(wires))
            .build()
    }

    private fun proxiesFieldOf(proxy: ClassName): FieldSpec {
        val factory = ParameterizedTypeName.get(JavaNames.FACTORY, proxy)
        return FieldSpec.builder(factory, "PROXIES", PUBLIC, STATIC, FINAL).initializer("\$T::new", proxy).build()
    }

    private fun overrideMethodOf(wire: Wire): MethodSpec {
        val crossing = wire.crossing
        val override = overrideOf(crossing.method.simpleName.toString(), TypeName.get(crossing.result.type))
        wire.parameters.forEach { override.addParameter(TypeName.get(it.operand.type), it.place.argument) }
        return override.addCode(senderBodyOf(wire)).build()
    }

    private fun senderBodyOf(wire: Wire): CodeBlock {
        val body = SenderBody(pending)
        val block = wire.result.sendResultSlots(body)
        val parameters = wire.parameters.flatMap { it.send(body) }
        val transport = wire.transport.send(body)
        wire.result.receiveResult(body, sendCall(body, wire, transport + block + parameters))
        return CodeBlock.builder()
            .addStatement("foreignCheck()")
            .add(body.checks.build())
            .addStatement("\$T thread = \$T.thread()", threadData, threadData.enclosingClassName())
            .add(body.prepare.build())
            .add(wire.transport.bracketOf(body))
            .build()
    }

    private fun receiverBodyOf(wire: Wire): CodeBlock {
        val body = ReceiverBody()
        body.statements.addStatement("\$T receiver = HANDLES.object(handle)", ClassName.get(wire.proxy.type))
        wire.transport.receive(body)
        val arguments = wire.parameters.map { it.receive(body) }
        val call = CodeBlock.of("receiver.\$N(\$L)", wire.crossing.method.simpleName, CodeBlock.join(arguments, ", "))
        wire.result.sendResult(body, call)
        val code = CodeBlock.builder()
            .beginControlFlow("try")
            .add(body.statements.build())
            .nextControlFlow("catch (\$T t)", Throwable::class.java)
            .addStatement("\$L", raise)
        if (wire.result.resultType != TypeName.VOID) code.addStatement("return \$L", zeroOf(wire.result.resultType))
        return code.endControlFlow().build()
    }
}
