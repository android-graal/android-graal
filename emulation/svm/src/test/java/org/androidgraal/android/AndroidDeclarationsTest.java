    private static final String DEPRECATED = "Ljava/lang/Deprecated;";

    private static final String EMULATED = "Lorg/androidgraal/hosted/annotate/Emulated;";

    private enum Tree {
        EMULATIONS("android.emulations"), DECLARATIONS("android.declarations");

        private final String property;

        Tree(String property) {
            this.property = property;
        }

        private Path root() {
            return Path.of(System.getProperty(property));
        }

        private Path classFile(String internalName) {
            return root().resolve(internalName + ".class");
        }
    }

    private static List<Arguments> classes() throws IOException {
        List<Arguments> classes = new ArrayList<>();
        for (Tree tree : Tree.values()) {
            Path root = tree.root();
            try (Stream<Path> files = Files.walk(root.resolve("android"))) {
                files.map(root::relativize).map(path -> path.toString().replace('\\', '/'))
                        .filter(name -> name.endsWith(".class")).map(name -> name.substring(0, name.length() - 6))
                        .filter(name -> !isInvisible(root, name) && !isHiddenNested(name)).sorted()
                        .forEach(name -> classes.add(Arguments.of(tree, name)));
            }
        }
        return classes;
    }

    private static boolean isInvisible(Path root, String internalName) {
        try {
            ClassModel model = ClassFile.of().parse(root.resolve(internalName + ".class"));
            return model.findAttribute(Attributes.innerClasses())
                    .map(attribute -> attribute.classes().stream()
                            .anyMatch(info -> info.innerClass().asInternalName().equals(internalName)
                                    && (info.flags().contains(AccessFlag.PRIVATE) || info.outerClass().isEmpty())))
                    .orElse(false);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static boolean isHiddenNested(String internalName) {
        int nested = internalName.lastIndexOf('$');
        return nested > 0
                && HIDDEN.getOrDefault(internalName.substring(0, nested), Set.of()).contains("nested " + internalName);
    }

